# Builds runtime\src\subtitles_en.inc (the built-in English subtitles, subtitles.cpp) from runtime\subtitles\voice_lines.tsv.
#
# voice_lines.tsv: one row per voice clip, tab-separated, with a header row:
#   bank     A or B (the effect bank, see subtitles.cpp; all the voice is in B)
#   number   effect number within that bank (= sample number in its sample bank)
#   ms       the clip's length at its base pitch (22050 Hz)
#   speaker  who says it, where known (not shown in game)
#   japanese what is said, as heard (Whisper transcription corrected by hand)
#   english  the subtitle; empty = no subtitle for this clip (shouts, grunts, sound effects)
#   note     "?" = not sure of the Japanese, worth checking by ear
#
# Usage: python scripts\subtitles.py           writes runtime\src\subtitles_en.inc
#        python scripts\subtitles.py --txt     also writes subtitles_en.txt (the format data\subtitles_en.txt
#                                              overrides the built-in lines with, to try fixes without a build)
import csv, os, sys

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # project folder (scripts\..)
SOURCE = os.path.join(BASE, "runtime", "subtitles", "voice_lines.tsv")
INC = os.path.join(BASE, "runtime", "src", "subtitles_en.inc")
TXT = os.path.join(BASE, "runtime", "subtitles", "subtitles_en.txt")


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    rows = list(csv.DictReader(open(SOURCE, encoding="utf-8", newline=""), delimiter="\t"))
    lines = [r for r in rows if r["english"].strip()]
    with open(INC, "w", encoding="utf-8", newline="\r\n") as out:
        out.write("// Generated by scripts\\subtitles.py from runtime\\subtitles\\voice_lines.tsv - edit that file instead.\n")
        for r in lines:
            out.write("{ '%s', %d, %d, %s },\n" % (r["bank"], int(r["number"]), int(r["ms"]), c_string(r["english"].strip())))
    print(f"{len(lines)} subtitles of {len(rows)} clips -> {INC}")
    if "--txt" in sys.argv:
        with open(TXT, "w", encoding="utf-8", newline="\n") as out:
            out.write("# bank\tnumber\tms\tenglish (copy to data\\subtitles_en.txt next to adam.exe to override the built-in lines)\n")
            for r in lines:
                out.write(f"{r['bank']}\t{int(r['number'])}\t{int(r['ms'])}\t{r['english'].strip()}\n")
        print(f"-> {TXT}")


if __name__ == "__main__":
    main()
